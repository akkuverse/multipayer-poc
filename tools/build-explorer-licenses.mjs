// Package the original licence texts in one offline, standalone HTML page.
// --check is read-only and runs on every supported runtime Node version.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT, requireGeneratorNode } from './explorer-inputs.mjs';

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  throw new Error('usage: node tools/build-explorer-licenses.mjs [--check]');
}
const check = args[0] === '--check';
if (!check) requireGeneratorNode();

const escape = (text) => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const sources = [
  ['bsl', 'Business Source License 1.1', 'LICENSE'],
  ['notices', 'Third-party notices and asset permissions', 'THIRD_PARTY_NOTICES.md'],
  ['react', 'React — MIT License', 'explorer/app/vendor/react/LICENSE'],
  ['react-dom', 'React DOM — MIT License', 'explorer/app/vendor/react-dom/LICENSE'],
  ['babel', 'Babel standalone — MIT License', 'explorer/app/vendor/babel-standalone/LICENSE'],
];
const sections = sources.map(([id, title, source]) => {
  const text = readFileSync(join(REPO_ROOT, source), 'utf8');
  return `<section id="${id}"><h2>${escape(title)}</h2>\n<pre>${escape(text)}</pre></section>`;
}).join('\n');
const html = `<!doctype html>
<!-- Generated by tools/build-explorer-licenses.mjs. Do not hand-edit. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Licences — Multi-payer explorer</title>
<style>
  body { margin: 0; padding: 24px; background: #F8F9F8; color: #1B4332; font: 17px/1.6 system-ui, sans-serif; }
  main { max-width: 960px; margin: 0 auto; }
  a { color: #2D6A4F; text-underline-offset: 3px; }
  nav { display: flex; flex-wrap: wrap; gap: 8px 24px; }
  section { margin-top: 40px; border-top: 1px solid #B7C9BF; }
  pre { white-space: pre-wrap; overflow-wrap: anywhere; font: 15px/1.6 ui-monospace, monospace; }
</style>
</head>
<body><main>
<a href="./">Back to the explorer</a>
<h1>Licences and notices</h1>
<p>The explorer's own code uses the Business Source License 1.1. Bundled third-party components retain their own licences. The notices below also describe the limited permission for bundled Akku assets.</p>
<nav aria-label="Licence sections">
${sources.map(([id, title]) => `<a href="#${id}">${escape(title)}</a>`).join('\n')}
</nav>
${sections}
</main></body>
</html>
`;
const target = join(REPO_ROOT, 'explorer/licenses.html');
if (check) {
  if (readFileSync(target, 'utf8') !== html) {
    throw new Error('explorer/licenses.html is stale; run pnpm explorer:build');
  }
  console.log('Explorer licences match the source texts.');
} else {
  writeFileSync(target, html);
  console.log('Generated explorer/licenses.html');
}
